DEFAULT_JUDGE = {'CORE': 'TRUE_CORE', 'CHAIN': 'TRUE_CHAIN',
                 'UNCERTAIN': 'TRUE_UNC', 'EXCLUDE': 'TRUE_EXCL'}


def main():
    sample = list(csv.DictReader(open(SAMPLE_PATH, 'r', encoding='utf-8-sig', newline='')))
    rows = []
    n_over = 0
    for r in sample:
        key = (r['主题'], r['代码'])
        if key in OVERRIDE:
            j, lv, reason = OVERRIDE[key]
            n_over += 1
        else:
            j = DEFAULT_JUDGE[r['系统分类']]
            mb = (r['主营文本'] or '').strip()
            if r['系统分类'] == 'UNCERTAIN':
                lv = 'D' if not mb else 'C'
                reason = '主营文本缺失，无外部资料可确认，保留待补录（不判 EXCL）' if not mb \
                    else '主营文本过短，无外部资料可确认，保留待补录'
            else:
                lv, reason = 'B', '公司披露主营/产品与主题一致，系统判定成立'
        rows.append({'主题': r['主题'], '代码': r['代码'], '名称': r['名称'],
                     '人工分类': j, '证据等级': lv, '人工理由': reason})

    with open(JUDGE_PATH, 'w', encoding='utf-8-sig', newline='') as f:
        w = csv.DictWriter(f, fieldnames=['主题', '代码', '名称', '人工分类', '证据等级', '人工理由'])
        w.writeheader()
        w.writerows(rows)
    print(f'判定回填完成 -> {JUDGE_PATH}')
    print(f'  样本 {len(rows)} 条，其中逐条覆盖判定 {n_over} 条，其余沿用系统判定')


if __name__ == '__main__':
    main()
