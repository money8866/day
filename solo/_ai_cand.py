def get_txt(code):
    if not agg:
        return '<NO_AGG>'
    r = agg.get(code)
    if isinstance(r, str):
        return r
    if isinstance(r, dict):
        return (r.get('mainbiz') or r.get('main_business') or r.get('business') or '<无>')
    return '<无>'

